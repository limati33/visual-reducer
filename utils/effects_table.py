# ------------------------------------------------------------
# ANSI-safe helpers
# ------------------------------------------------------------

ANSI_RE = re.compile(r'\x1b\[[0-9;]*m')

def strip_ansi(s: str) -> str:
    return ANSI_RE.sub('', s)

def pad_visible(s: str, width: int) -> str:
    visible = wcswidth(strip_ansi(s))
    if visible < width:
        return s + ' ' * (width - visible)
    return s

