import cv2
import numpy as np
import re
from pathlib import Path

def _get_idx(base_name):
    if not base_name:
        return 0
    m = re.search(r'(\d+)', base_name)
    return int(m.group(1)) if m else 0

def apply_retrolcd(img, w, h, out_dir=None, base_name=None):
    # Пикселизация
    small = cv2.resize(img, (w//2, h//2), interpolation=cv2.INTER_NEAREST)
    up = cv2.resize(small, (w, h), interpolation=cv2.INTER_NEAREST)

    up = up.astype(np.float32) / 255.0

    # Эффект неравномерной подсветки экрана
    line = np.linspace(0.9, 1.05, h, dtype=np.float32).reshape(h, 1)
    lcd = up * line[..., None] + 0.08
    lcd = np.clip(lcd, 0, 1)

    gray = cv2.cvtColor(lcd, cv2.COLOR_BGR2GRAY)

    # --- МАГИЯ ДИЗЕРИНГА (Bayer Matrix 4x4) ---
    # Создает "шахматный" паттерн для плавных градиентов
    bayer = np.array([
        [ 0,  8,  2, 10],
        [12,  4, 14,  6],
        [ 3, 11,  1,  9],
        [15,  7, 13,  5]
    ], dtype=np.float32) / 16.0 - 0.5
    
    # Размножаем матрицу на весь размер изображения
    tiles_y = int(np.ceil(h / 4))
    tiles_x = int(np.ceil(w / 4))
    dither_matrix = np.tile(bayer, (tiles_y, tiles_x))[:h, :w]
    
    # Смешиваем яркость картинки с матрицей (0.25 - идеальная сила для 4 цветов)
    gray = np.clip(gray + dither_matrix * 0.25, 0, 1)
    # ------------------------------------------

    palettes = [
        # --- ТВОИ ОРИГИНАЛЬНЫЕ ПАЛИТРЫ ---
        [[15, 56, 15], [48, 98, 48], [139, 172, 15], [155, 188, 15]], # 0: Классический GameBoy
        [[0, 10, 30], [0, 60, 120], [0, 120, 200], [120, 200, 255]], # 1: Океан / Глубина
        [[0, 0, 0], [0, 0, 80], [0, 0, 180], [20, 20, 255]], # 2: Неон Синий
        [[5, 20, 5], [10, 80, 10], [30, 180, 30], [180, 255, 180]], # 3: Токсичный зеленый
        [[50, 10, 40], [120, 40, 120], [200, 200, 50], [255, 200, 255]], # 4: Пурпурно-желтый закат
        [[25, 25, 25], [80, 80, 80], [160, 160, 160], [220, 225, 230]], # 5: Холодный ЧБ
        [[59, 9, 18], [124, 12, 130], [67, 20, 186], [25, 107, 250]], # 6: Синтвейв
        [[40, 20, 0], [100, 60, 0], [180, 140, 50], [255, 240, 200]], # 7: Ржавчина / Песок
        [[10, 0, 20], [40, 10, 60], [80, 20, 120], [180, 150, 255]], # 8: Мистика / Фиолетовый
        [[40, 20, 0], [100, 100, 0], [200, 255, 100], [255, 255, 200]], # 9: Латунь / Золото
        [[10, 10, 10], [99, 99, 90], [151, 156, 98], [220, 227, 141]], # 10: Старый пергамент
        [[12, 18, 8], [40, 70, 20], [95, 150, 60], [190, 235, 150]], # 11: Лес / Камуфляж
        [[20, 5, 35], [70, 25, 90], [140, 60, 170], [230, 180, 245]], # 12: Аметист
        [[0, 25, 35], [20, 80, 110], [60, 150, 190], [180, 240, 255]], # 13: Бирюзовый лёд

        # --- НОВЫЕ ПАЛИТРЫ ---
        
        # Ретро устройства & Компьютеры
        [[0, 0, 0], [80, 0, 0], [160, 0, 0], [255, 0, 0]], # 14: Virtual Boy (Чистый красный на черном)
        [[0, 0, 0], [170, 0, 170], [0, 170, 170], [255, 255, 255]], # 15: CGA палитра 1 (Маджента и Циан)
        [[0, 0, 0], [170, 85, 0], [85, 255, 85], [255, 255, 85]], # 16: CGA палитра 2 (Красно-зелено-желтая)
        [[20, 20, 20], [90, 90, 90], [180, 180, 180], [240, 240, 240]], # 17: Macintosh Classic (Мягкий монохром)
        [[0, 15, 0], [0, 80, 0], [0, 180, 0], [100, 255, 100]], # 18: Терминал Матрицы (Контрастный зеленый)

        # Атмосфера & Природа
        [[43, 30, 24], [105, 76, 58], [176, 140, 107], [236, 214, 186]], # 19: Сепия (Старая фотография)
        [[20, 0, 5], [90, 10, 20], [180, 40, 30], [255, 120, 80]], # 20: Кровавая луна (Темно-бордовый в оранжевый)
        [[40, 10, 0], [120, 40, 0], [200, 100, 20], [255, 200, 80]], # 21: Осенний костёр
        [[0, 10, 20], [10, 60, 100], [50, 150, 200], [200, 240, 255]], # 22: Арктический ледник

        # Киберпанк & Эстетика
        [[20, 0, 30], [80, 0, 100], [180, 0, 180], [255, 100, 255]], # 23: Киберпанк неон (Только розовый/пурпурный)
        [[10, 0, 40], [60, 10, 120], [200, 50, 180], [0, 255, 255]], # 24: Vaporwave (От темно-синего через мадженту в циан)
        [[5, 0, 15], [30, 20, 60], [100, 60, 100], [255, 150, 150]], # 25: Пастельный Ло-Фай (Lo-Fi закат)
        
        # Экспериментальные (Высокий контраст)
        [[10, 15, 20], [10, 80, 120], [240, 100, 40], [255, 220, 180]], # 26: Teal & Orange (Киношный цветкор)
        [[30, 0, 60], [150, 0, 50], [220, 80, 0], [255, 200, 0]] # 27: Магический огонь (Фиолетовый -> Красный -> Желтый)
    ]

    # Вспомогательная функция, чтобы не дублировать код
    def map_to_palette(grayscale_img, pal_rgb):
        pal_arr = np.array(pal_rgb, dtype=np.float32) / 255.0
        # Исправленная математика: умножаем на len(), а не на len()-1
        idx = np.floor(grayscale_img * len(pal_arr)).astype(np.int32)
        idx = np.clip(idx, 0, len(pal_arr) - 1)
        return pal_arr[idx]

    # --- основной результат ---
    result_main = map_to_palette(gray, palettes[0])

    # --- дополнительные сохраняем ---
    if out_dir:
        Path(out_dir).mkdir(parents=True, exist_ok=True)

        for idx, pal in enumerate(palettes[1:], start=1):
            res = (map_to_palette(gray, pal) * 255).astype(np.uint8)
            safe_name = Path(base_name).stem if base_name else "image"
            path = Path(out_dir) / f"{safe_name}_lcd_{idx}.png"
            cv2.imwrite(str(path), res)

    return (result_main * 255).astype(np.uint8)